static int decode(const unsigned char *input, size_t size, enum xz_ret expected_result)
{
    unsigned char expected[256];
    for (unsigned int i = 0; i < 32; ++i)
    {
        unsigned int offset = 0x1000 - i * 8;
        expected[i * 8]     = 0xe8;
        for (unsigned int j = 0; j < 4; ++j)
            expected[i * 8 + 1 + j] = (unsigned char) (offset >> (j * 8));
        memset(expected + i * 8 + 5, 0x90, 3);
    }
    unsigned char  output[sizeof(expected)];
    struct xz_dec *decoder = xz_dec_init(XZ_SINGLE, 0);
    if (decoder == NULL)
        return 1;
    struct xz_buf buffer = {.in = input, .in_size = size, .out = output, .out_size = sizeof(output)};
    enum xz_ret   result = xz_dec_run(decoder, &buffer);
    xz_dec_end(decoder);
    if (result != expected_result)
        return 1;
    return result == XZ_STREAM_END && (buffer.in_pos != size || buffer.out_pos != sizeof(expected) ||
                                       memcmp(output, expected, sizeof(expected)) != 0);
}

int main(void)
{
    xz_crc32_init();
    if (decode(crc32_stream, sizeof(crc32_stream), XZ_STREAM_END) ||
        decode(crc64_stream, sizeof(crc64_stream), XZ_OPTIONS_ERROR) ||
        decode(sha256_stream, sizeof(sha256_stream), XZ_OPTIONS_ERROR) ||
        decode(arm_stream, sizeof(arm_stream), XZ_OPTIONS_ERROR))
    {
        fputs("XZ decoder feature test failed\n", stderr);
        return 1;
    }

    unsigned char corrupted[sizeof(crc32_stream)];
    memcpy(corrupted, crc32_stream, sizeof(corrupted));
    corrupted[sizeof(corrupted) - 1] ^= 1;
    return decode(corrupted, sizeof(corrupted), XZ_DATA_ERROR);
}
